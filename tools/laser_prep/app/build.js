/**
 * @file build.js
 * @version 0.3
 * @author Samuel Cao
 * @created 2026-10-30
 * @lastUpdated 2026-11-02
 * @description Inlines the vendored libraries and src/*.js (order in build_order.json) into src/page.html and writes the single offline file laser_prep_v<VERSION>.html.
 * @aiUpdate Update @lastUpdated and @version. Keep the filename. Append changelog at bottom.
 *
 * Usage: node build.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const VERSION = '0.3';
const SRC = path.join(__dirname, 'src');
const ORDER = require('./build_order.json');
const today = new Date().toISOString().slice(0, 10);
const out = `laser_prep_v${VERSION}.html`;

const scripts = ORDER.map(f => {
  const code = fs.readFileSync(path.join(SRC, f), 'utf8');
  // A literal closing script tag inside a library would end the inline script early.
  const safe = code.replace(/<\/script/gi, '<\\/script');
  return `<script>\n// ---- ${f} ----\n${safe}\n</script>`;
}).join('\n');

const meta = `<!--
  file: ${out}
  version: ${VERSION}
  author: Samuel Cao
  created: 2026-10-30
  last_updated: ${today}
  description: Laser prep app prototype. Load DXF or SVG files, add shapes, text, images, test patterns, and boxes; lay out, color, tab, and join parts; save a laser-ready PDF (or DXF, SVG, or print). Works offline.
  bundled: Clipper 6.1.3a (Boost Software License 1.0), SVGnest geometryutil, placementworker, and genetic search (MIT, Jack Qiao), opentype.js 1.3.4 (MIT), fonts Label Sans and Allerta Stencil (SIL OFL 1.1) and Hershey Simplex (public domain). License texts: src/vendor/.
  ai_update: Do not edit this file by hand. Edit src/ and run node build.js, which writes this file. Bump VERSION in build.js and append to the changelog in build.js.
-->`;

const changelog = `<!-- CHANGELOG
  v0.1 (2026-10-30): First prototype, built from core design v1.1. 33/33 fixtures pass; PDF, SVG, and DXF output validated.
  v0.2 (2026-10-30): PDF asks viewers not to scale (/PrintScaling /None); DXF header has real extents and limits.
  v0.3 (2026-11-02): Phase 2: many objects, shapes, text (bundled and PC fonts, on a path), images with cut outlines, test patterns, box generator, copies, repeat with a list, arrange (rectangles, true outlines, SVGnest), align and snap, holding tabs, fingers, tab-and-slot, kerf compensation, file colors, resize with a warning, undo.
-->`;

let html = fs.readFileSync(path.join(SRC, 'page.html'), 'utf8');
html = html.replace('<!--META-->', meta).replace('<!--SCRIPTS-->', scripts) + changelog + '\n';
fs.writeFileSync(path.join(__dirname, out), html);
console.log(`wrote ${out} (${Math.round(html.length / 1024)} KB)`);

